export function getFleetInfo(assetOrTag = '') {
  if (!assetOrTag) return null;
  const clean = String(assetOrTag).trim().toUpperCase();
  const digits = clean.replace(/^[A-Z]+/i, '');
  return FLEET_FULLTAG_MAP.get(clean) || FLEET_TAG_MAP.get(digits) || null;
}
